const runAiTask = async (action, prompt, content) => {
  const promptText = getPromptForAction(action, prompt, content);
  
  if (process.env.GEMINI_API_KEY) {
    const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: promptText,
    });
    return response.text || '';
  } else {
    return getMockupText(action, prompt, content);
  }
};

const runAiTaskStream = async (action, prompt, content, onChunk, onDone) => {
  const promptText = getPromptForAction(action, prompt, content);
  
  if (process.env.GEMINI_API_KEY) {
    const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
    const responseStream = await ai.models.generateContentStream({
      model: 'gemini-2.5-flash',
      contents: promptText,
    });
    for await (const chunk of responseStream) {
      if (chunk.text) {
        onChunk(chunk.text);
      }
    }
    if (onDone) onDone();
  } else {
    // Offline simulation
    const mockupText = getMockupText(action, prompt, content);
    const words = mockupText.split(' ');
    let i = 0;
    
    return new Promise((resolve) => {
      const interval = setInterval(() => {
        if (i < words.length) {
          const chunk = words.slice(i, i + 4).join(' ') + ' ';
          onChunk(chunk);
          i += 4;
        } else {
          clearInterval(interval);
          if (onDone) onDone();
          resolve();
        }
      }, 100);
    });
  }
};

module.exports = {
  getPromptForAction,
  getMockupText,
  runAiTask,
  runAiTaskStream,
};
