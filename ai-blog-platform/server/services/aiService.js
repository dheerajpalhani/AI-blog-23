const { GoogleGenAI } = require('@google/genai');

const getPromptForAction = (action, prompt, content) => {
  switch (action) {
    case 'generate':
      return `Write a high-quality, engaging blog post about: "${prompt}". Return it in beautiful HTML format suitable for rendering inside a rich-text editor (using tags like <h2>, <p>, <ul>, <li>, and <strong>). Do not include markdown fences, HTML wrapper tags like <html>, <head>, <body>, or code blocks unless requested. Keep it around 400 words.`;
    case 'continue':
      return `Given the following partial content of a blog post, continue writing the next section naturally. Keep the tone and style consistent. Return ONLY the new continued content in HTML format without markdown fences or HTML wrappers:\n\n${content}`;
    case 'rewrite':
      return `Rewrite the following blog content to make it more professional, engaging, and polished. Keep it in HTML format without markdown fences or HTML wrappers:\n\n${content}`;
    case 'grammar':
      return `Fix any grammar, spelling, and punctuation errors in the following blog content while preserving its original meaning and HTML tags. Return the polished version in HTML format without markdown fences or HTML wrappers:\n\n${content}`;
    case 'summarize':
      return `Create a concise, professional summary of the following blog content. Return it in HTML format (using <p> and bullet points if needed) without markdown fences or HTML wrappers:\n\n${content}`;
    case 'meta':
      return `Generate a high-quality SEO meta description (under 160 characters) for a blog post with the following content. Return ONLY the plain text meta description without quotes:\n\n${content}`;
    case 'titles':
      return `Generate 5 catchy, SEO-friendly headlines/titles for a blog post about "${prompt || ''}" (or with content "${content || ''}"). Return them as a clean HTML bulleted list (<ul> and <li> tags) without markdown fences or HTML wrappers.`;
    case 'tags':
      return `Generate 8 relevant, trending hashtags/tags for a blog post with the following content. Return them as a comma-separated list of hashtags (e.g. #WebDev, #AI, #Tech) in plain text:\n\n${content}`;
    default:
      return prompt || '';
  }
};

